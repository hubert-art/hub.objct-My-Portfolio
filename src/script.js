const typingWords = {
    en: ["enjoy using.", "remember.", "trust."],
    fr: ["aiment utiliser.", "retiennent.", "peuvent adopter."]
};

let currentLanguage = localStorage.getItem("portfolio-language") || "en";
let typingIndex = 0;
let typingChar = 0;
let deleting = false;
let typingTimer;

const languageToggle = document.querySelector("[data-language-toggle]");
const languageFlag = document.querySelector("[data-language-flag]");
const languageLabel = document.querySelector("[data-language-label]");
const typingTarget = document.querySelector("[data-typing]");
const menuToggle = document.querySelector(".menu-toggle");
const navPanel = document.querySelector(".nav-panel");
const navLinks = document.querySelectorAll(".nav-links a");
const revealItems = document.querySelectorAll(".reveal");
const counters = document.querySelectorAll("[data-counter]");
const testimonials = document.querySelectorAll(".testimonial");
const contactForm = document.querySelector(".contact-form");
const statusText = document.querySelector(".form-status");

function applyLanguage(language) {
    currentLanguage = language;
    localStorage.setItem("portfolio-language", language);
    document.documentElement.lang = language;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.getAttribute("data-i18n");
        const value = translations[language][key];
        if (value) element.textContent = value;
    });

    languageFlag.textContent = language === "en" ? "🇫🇷" : "🇬🇧";
    languageLabel.textContent = language === "en" ? "FR" : "EN";
    typingIndex = 0;
    typingChar = 0;
    deleting = false;
    clearTimeout(typingTimer);
    typeText();
}

function typeText() {
    const words = typingWords[currentLanguage];
    const word = words[typingIndex % words.length];

    typingTarget.textContent = word.slice(0, typingChar);

    if (!deleting && typingChar < word.length) {
        typingChar += 1;
        typingTimer = setTimeout(typeText, 70);
        return;
    }

    if (!deleting && typingChar === word.length) {
        deleting = true;
        typingTimer = setTimeout(typeText, 1300);
        return;
    }

    if (deleting && typingChar > 0) {
        typingChar -= 1;
        typingTimer = setTimeout(typeText, 38);
        return;
    }

    deleting = false;
    typingIndex += 1;
    typingTimer = setTimeout(typeText, 220);
}

function closeMenu() {
    document.body.classList.remove("menu-open");
    menuToggle.setAttribute("aria-expanded", "false");
}

function startCounters() {
    counters.forEach((counter) => {
        if (counter.dataset.counted) return;
        counter.dataset.counted = "true";

        const target = Number(counter.dataset.counter);
        const duration = 1200;
        const start = performance.now();

        function update(now) {
            const progress = Math.min((now - start) / duration, 1);
            const eased = 1 - Math.pow(1 - progress, 3);
            counter.textContent = Math.round(target * eased);
            if (progress < 1) requestAnimationFrame(update);
        }

        requestAnimationFrame(update);
    });
}

const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("active");
        if (entry.target.classList.contains("stats-grid")) startCounters();
        revealObserver.unobserve(entry.target);
    });
}, { threshold: 0.16 });

revealItems.forEach((item, index) => {
    item.style.transitionDelay = `${Math.min(index % 5, 4) * 70}ms`;
    revealObserver.observe(item);
});

const sectionObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        navLinks.forEach((link) => {
            link.classList.toggle("active", link.getAttribute("href") === `#${entry.target.id}`);
        });
    });
}, { rootMargin: "-42% 0px -48% 0px" });

document.querySelectorAll("main section[id]").forEach((section) => sectionObserver.observe(section));

let testimonialIndex = 0;
setInterval(() => {
    testimonials[testimonialIndex].classList.remove("active");
    testimonialIndex = (testimonialIndex + 1) % testimonials.length;
    testimonials[testimonialIndex].classList.add("active");
}, 4200);

languageToggle.addEventListener("click", () => {
    applyLanguage(currentLanguage === "en" ? "fr" : "en");
});

menuToggle.addEventListener("click", () => {
    const isOpen = document.body.classList.toggle("menu-open");
    menuToggle.setAttribute("aria-expanded", String(isOpen));
});

navPanel.addEventListener("click", (event) => {
    if (event.target.closest("a")) closeMenu();
});

contactForm.addEventListener("submit", (event) => {
    event.preventDefault();
    const fields = [...contactForm.querySelectorAll("input, textarea, select")];
    const email = contactForm.querySelector("input[type='email']");
    const emailIsValid = /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.value.trim());
    let valid = true;

    fields.forEach((field) => {
        const fieldIsValid = field.value.trim().length > 0 && (field !== email || emailIsValid);
        field.classList.toggle("field-error", !fieldIsValid);
        if (!fieldIsValid) valid = false;
    });

    if (!valid) {
        statusText.textContent = translations[currentLanguage]["form.error"];
        return;
    }

    const data = new FormData(contactForm);
    const subject = encodeURIComponent(`Portfolio inquiry: ${data.get("project")}`);
    const body = encodeURIComponent(`Name: ${data.get("name")}\nEmail: ${data.get("email")}\n\n${data.get("message")}`);
    window.location.href = `mailto:lubulahubert@mail.com?subject=${subject}&body=${body}`;
    statusText.textContent = translations[currentLanguage]["form.success"];
    contactForm.reset();
});

document.querySelector("[data-year]").textContent = new Date().getFullYear();
applyLanguage(currentLanguage);
